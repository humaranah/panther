namespace Panther.Core.Audio.Enums;

/// <summary>
/// Represents the format of audio samples.
/// </summary>
public enum SampleFormat
{
    /// <summary>
    /// Represents a 16-bit integer sample format.
    /// </summary>
    Int16,
    /// <summary>
    /// Represents a 24-bit packed or 32-bit padded integer sample format.
    /// </summary>
    Int24,
    /// <summary>
    /// Represents a 32-bit integer sample format.
    /// </summary>
    Int32,
    /// <summary>
    /// Represents a 32-bit float sample format.
    /// </summary>
    Float32,
}
